-- ─── Views ───────────────────────────────────────────────────────────────────
CREATE OR REPLACE VIEW VW_TIMELINE_PET AS
SELECT
    a.ID_AGENDAMENTO,
    a.ID_PET,
    p.NM_PET,
    a.DT_AGENDAMENTO,
    a.DS_TIPO         AS DS_TIPO_EVENTO,
    a.ST_STATUS,
    a.ID_CLINICA,
    c.NM_CLINICA
FROM   AGENDAMENTO a
JOIN   PET          p ON p.ID_PET     = a.ID_PET
JOIN   CLINICA      c ON c.ID_CLINICA = a.ID_CLINICA
WHERE  a.ID_PET IS NOT NULL;

COMMENT ON TABLE VW_TIMELINE_PET IS 'Linha do tempo de atendimentos por pet — lida pelo Java (TimelineService).';

CREATE OR REPLACE VIEW VW_VACINAS_VENCENDO AS
SELECT
    p.ID_PET,
    p.NM_PET,
    a.ID_TUTOR,
    a.DT_AGENDAMENTO              AS DT_VACINA,
    a.ID_CLINICA,
    c.NM_CLINICA
FROM   AGENDAMENTO a
JOIN   PET         p ON p.ID_PET     = a.ID_PET
JOIN   CLINICA     c ON c.ID_CLINICA = a.ID_CLINICA
WHERE  a.DS_TIPO   = 'VACINA'
  AND  a.ST_STATUS NOT IN ('CANCELADO','REALIZADO')
  AND  a.DT_AGENDAMENTO >= CURRENT_TIMESTAMP
  AND  a.DT_AGENDAMENTO <= CURRENT_TIMESTAMP + INTERVAL '30' DAY;

COMMENT ON TABLE VW_VACINAS_VENCENDO IS 'Vacinas agendadas nos próximos 30 dias — alertas preventivos.';
