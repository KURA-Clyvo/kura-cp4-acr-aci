-- ─── 1. CLINICA (.NET owns — Java read-only) ─────────────────────────────────
CREATE TABLE CLINICA (
    ID_CLINICA      NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_CLINICA      VARCHAR2(120) NOT NULL,
    NR_CNPJ         VARCHAR2(18)  NOT NULL,
    DS_ENDERECO     VARCHAR2(200),
    NM_CIDADE       VARCHAR2(80),
    SG_UF           CHAR(2),
    NR_CEP          VARCHAR2(9),
    DS_TELEFONE     VARCHAR2(20),
    DS_EMAIL        VARCHAR2(120),
    -- Campos de acesso da clínica (.NET auth)
    DS_EMAIL_ACESSO VARCHAR2(120),
    DS_SENHA_HASH   VARCHAR2(256),
    DT_CADASTRO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ST_ATIVA        CHAR(1)   DEFAULT 'S' NOT NULL,
    CONSTRAINT UK_CLINICA_CNPJ         UNIQUE (NR_CNPJ),
    CONSTRAINT UK_CLINICA_EMAIL_ACESSO UNIQUE (DS_EMAIL_ACESSO),
    CONSTRAINT CHK_CLINICA_ATIVA       CHECK  (ST_ATIVA IN ('S','N'))
);

COMMENT ON TABLE  CLINICA             IS 'Clínicas veterinárias — owned pelo .NET (Felipe). Java lê via @Immutable.';
COMMENT ON COLUMN CLINICA.DS_SENHA_HASH IS 'Hash BCrypt da senha de acesso ao painel da clínica — gerenciado pelo .NET.';

-- ─── 2. ESPECIE (.NET owns — Java read-only, cached) ─────────────────────────
CREATE TABLE ESPECIE (
    ID_ESPECIE  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_ESPECIE  VARCHAR2(50) NOT NULL,
    CONSTRAINT UK_ESPECIE_NOME UNIQUE (NM_ESPECIE)
);

COMMENT ON TABLE ESPECIE IS 'Espécies animais (Cão, Gato …). Cacheable — baixa mutabilidade.';

-- ─── 3. TIPO_EVENTO (referência — .NET manages) ───────────────────────────────
CREATE TABLE TIPO_EVENTO (
    ID_TIPO_EVENTO  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_TIPO         VARCHAR2(60)  NOT NULL,
    DS_TIPO         VARCHAR2(200),
    ST_ATIVO        CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT UK_TIPO_EVENTO_NM  UNIQUE (NM_TIPO),
    CONSTRAINT CHK_TIPO_EVENTO_ST CHECK  (ST_ATIVO IN ('S','N'))
);

COMMENT ON TABLE TIPO_EVENTO IS 'Catálogo de tipos de evento clínico (CONSULTA, VACINA …).';

-- ─── 4. RACA (.NET owns — Java read-only, cached) ────────────────────────────
CREATE TABLE RACA (
    ID_RACA         NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ESPECIE      NUMBER(10)   NOT NULL,
    NM_RACA         VARCHAR2(80) NOT NULL,
    DS_PREDISPOSICAO VARCHAR2(500),
    CONSTRAINT FK_RACA_ESPECIE FOREIGN KEY (ID_ESPECIE) REFERENCES ESPECIE(ID_ESPECIE)
);

COMMENT ON TABLE RACA IS 'Raças por espécie. Cacheable — baixa mutabilidade.';

-- ─── 5. VETERINARIO (.NET owns — Java read-only) ─────────────────────────────
CREATE TABLE VETERINARIO (
    ID_VETERINARIO  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA      NUMBER(10)    NOT NULL,
    NM_VETERINARIO  VARCHAR2(150) NOT NULL,
    NR_CRMV         VARCHAR2(20),
    DS_EMAIL        VARCHAR2(150),
    NR_TELEFONE     VARCHAR2(20),
    ST_ATIVO        CHAR(1) DEFAULT 'S' NOT NULL,
    DT_CRIACAO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_VET_CLINICA  FOREIGN KEY (ID_CLINICA) REFERENCES CLINICA(ID_CLINICA),
    CONSTRAINT UK_VET_CRMV     UNIQUE (NR_CRMV),
    CONSTRAINT CHK_VET_ATIVO   CHECK  (ST_ATIVO IN ('S','N'))
);

COMMENT ON TABLE VETERINARIO IS 'Veterinários vinculados à clínica — owned pelo .NET.';

-- ─── 6. TUTOR (.NET owns — Java read-only) ───────────────────────────────────
-- Nota: NR_CPF VARCHAR2(11) = 11 dígitos sem máscara (exigência da task)
-- Colunas mapeadas pela entity Java atual (T13 alinha ao v4 canônico):
--   ds_telefone  → v4 target: NR_TELEFONE (T13 renomeia)
--   dt_cadastro  → v4 target: DT_CRIACAO  (T13 renomeia)
CREATE TABLE TUTOR (
    ID_TUTOR            NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA          NUMBER(10)    NOT NULL,
    NM_TUTOR            VARCHAR2(200) NOT NULL,
    NR_CPF              VARCHAR2(11)  NOT NULL,
    DS_EMAIL            VARCHAR2(150) NOT NULL,
    DS_TELEFONE         VARCHAR2(20)  NOT NULL,
    DS_WHATSAPP         VARCHAR2(20),
    -- Campos extras mapeados pela entity atual (T13 revisa)
    DT_NASCIMENTO       DATE,
    DS_ENDERECO         VARCHAR2(200),
    NM_CIDADE           VARCHAR2(80),
    SG_UF               CHAR(2),
    NR_CEP              VARCHAR2(9),
    DT_CADASTRO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO      TIMESTAMP,
    ST_AVISO_PRIVACIDADE CHAR(1) DEFAULT 'N' NOT NULL,
    DT_AVISO_PRIVACIDADE TIMESTAMP,
    DS_VERSAO_AVISO     VARCHAR2(20),
    ST_ATIVO            CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_TUTOR_CLINICA           FOREIGN KEY (ID_CLINICA)  REFERENCES CLINICA(ID_CLINICA),
    CONSTRAINT UK_TUTOR_CPF               UNIQUE (NR_CPF),
    CONSTRAINT UK_TUTOR_EMAIL             UNIQUE (DS_EMAIL),
    CONSTRAINT CHK_TUTOR_AVISO_PRIVACIDADE CHECK  (ST_AVISO_PRIVACIDADE IN ('S','N')),
    CONSTRAINT CHK_TUTOR_ATIVO            CHECK  (ST_ATIVO IN ('S','N'))
);

COMMENT ON TABLE  TUTOR           IS 'Tutores dos pets — owned pelo .NET. Java lê via @Immutable.';
COMMENT ON COLUMN TUTOR.NR_CPF    IS 'CPF sem máscara, 11 dígitos.';
COMMENT ON COLUMN TUTOR.ST_AVISO_PRIVACIDADE IS 'S = tutor apresentado ao aviso de privacidade no balcão.';

-- ─── 7. PET (.NET owns — Java read-only) ─────────────────────────────────────
-- Campos nr_peso_kg, st_castrado, ds_alergias, ds_observacoes, dt_cadastro
-- mapeados pela entity Java atual (T13 remove campos legados após v4 align)
CREATE TABLE PET (
    ID_PET              NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA          NUMBER(10)     NOT NULL,
    ID_ESPECIE          NUMBER(10)     NOT NULL,
    ID_RACA             NUMBER(10),
    ID_VETERINARIO_RESP NUMBER(10),
    NM_PET              VARCHAR2(80)   NOT NULL,
    DT_NASCIMENTO       DATE,
    SG_SEXO             CHAR(1),
    -- Campos legados entity atual (T13 remove após v4 align):
    NR_PESO_KG          NUMBER(5,2),
    ST_CASTRADO         CHAR(1)  DEFAULT 'N' NOT NULL,
    DS_ALERGIAS         VARCHAR2(500),
    DS_OBSERVACOES      VARCHAR2(1000),
    DT_CADASTRO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- Campos v4 target:
    SG_PORTE            CHAR(1),
    ST_ATIVO            CHAR(1) DEFAULT 'S' NOT NULL,
    DT_CRIACAO          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DT_ATUALIZACAO      TIMESTAMP,
    CONSTRAINT FK_PET_CLINICA          FOREIGN KEY (ID_CLINICA)          REFERENCES CLINICA(ID_CLINICA),
    CONSTRAINT FK_PET_ESPECIE          FOREIGN KEY (ID_ESPECIE)          REFERENCES ESPECIE(ID_ESPECIE),
    CONSTRAINT FK_PET_RACA             FOREIGN KEY (ID_RACA)             REFERENCES RACA(ID_RACA),
    CONSTRAINT FK_PET_VET_RESP         FOREIGN KEY (ID_VETERINARIO_RESP) REFERENCES VETERINARIO(ID_VETERINARIO),
    CONSTRAINT CHK_PET_SEXO            CHECK (SG_SEXO IN ('M','F')),
    CONSTRAINT CHK_PET_PORTE           CHECK (SG_PORTE IN ('P','M','G')),
    CONSTRAINT CHK_PET_CASTRADO        CHECK (ST_CASTRADO IN ('S','N')),
    CONSTRAINT CHK_PET_ATIVO           CHECK (ST_ATIVO IN ('S','N'))
);

COMMENT ON TABLE  PET            IS 'Pets vinculados a tutores — owned pelo .NET.';
COMMENT ON COLUMN PET.SG_PORTE   IS 'P=Pequeno, M=Médio, G=Grande.';

