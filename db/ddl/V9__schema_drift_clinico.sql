-- =============================================================================
-- V9__schema_drift_clinico.sql
-- TASK-09 (INT-02). Corrige schema drift sistêmico entre o modelo EF Core do
-- .NET (backend-clinica-dotnet) e o schema real (Flyway/Oracle). O .NET tinha
-- 9 migrations EF "evidência" (nunca aplicadas em prod, por design — Flyway é
-- a única autoridade de DDL) cujas mudanças nunca foram espelhadas aqui. Isso
-- deixava praticamente toda a superfície clínica/IoT/notificação do .NET
-- (consultas, exames, vacinas, prescrições, documentos, notificações,
-- dispositivos IoT, triagem Luna) inutilizável — ORA-00904/ORA-00942 em
-- qualquer request que tocasse essas tabelas/colunas.
--
-- Descoberto e mapeado sistematicamente comparando cada
-- Kura.Infrastructure/Persistence/Configurations/*.cs contra V1+V4+V6+V7+V8
-- (+ variantes Oracle de V2/V3/V5). Ver docs/INT-02-contract-map.md.
-- =============================================================================

-- ─── 1. VETERINARIO — coluna de auditoria ausente ─────────────────────────────
ALTER TABLE VETERINARIO ADD DT_ATUALIZACAO TIMESTAMP;

-- ─── 2. ESPECIE — colunas de auditoria ausentes (DEFAULT retroage em linhas existentes) ──
ALTER TABLE ESPECIE ADD (
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP
);

-- ─── 3. RACA — colunas de auditoria ausentes ──────────────────────────────────
ALTER TABLE RACA ADD (
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP
);

-- ─── 4. TIPO_EVENTO — CD_TIPO (chave de negócio) + auditoria ──────────────────
-- CD_TIPO nasce nullable para permitir backfill dos 3 registros seed
-- (CONSULTA/TELEORIENTACAO/VACINA — NM_TIPO já está no formato de código),
-- só então vira NOT NULL + UNIQUE.
ALTER TABLE TIPO_EVENTO ADD (
    CD_TIPO        VARCHAR2(20),
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP
);
UPDATE TIPO_EVENTO SET CD_TIPO = NM_TIPO WHERE CD_TIPO IS NULL;
ALTER TABLE TIPO_EVENTO MODIFY CD_TIPO NOT NULL;
ALTER TABLE TIPO_EVENTO ADD CONSTRAINT UK_TIPO_EVENTO_CD UNIQUE (CD_TIPO);

-- ─── 5. INVITE_TUTOR — colunas de auditoria ausentes ──────────────────────────
ALTER TABLE INVITE_TUTOR ADD (
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP
);

-- ─── 6. EVENTO_CLINICO — de stub (só ID_PET/DT_EVENTO) para entidade real ─────
-- Tabela vazia (0 linhas) nesta base — NOT NULL direto sem necessidade de
-- backfill. ID_PET/DT_EVENTO/ID_EVENTO já existiam desde V1 (stub original).
ALTER TABLE EVENTO_CLINICO ADD (
    ID_CLINICA       NUMBER(10)     NOT NULL,
    ID_VETERINARIO   NUMBER(10)     NOT NULL,
    ID_TIPO_EVENTO   NUMBER(10)     NOT NULL,
    DS_OBSERVACAO    VARCHAR2(1000) NOT NULL,
    DT_CRIACAO       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO   TIMESTAMP
);
ALTER TABLE EVENTO_CLINICO ADD CONSTRAINT FK_EVENTO_CLINICA FOREIGN KEY (ID_CLINICA)     REFERENCES CLINICA(ID_CLINICA);
ALTER TABLE EVENTO_CLINICO ADD CONSTRAINT FK_EVENTO_VET     FOREIGN KEY (ID_VETERINARIO) REFERENCES VETERINARIO(ID_VETERINARIO);
ALTER TABLE EVENTO_CLINICO ADD CONSTRAINT FK_EVENTO_TIPO    FOREIGN KEY (ID_TIPO_EVENTO) REFERENCES TIPO_EVENTO(ID_TIPO_EVENTO);

COMMENT ON TABLE EVENTO_CLINICO IS '.NET owned. Entidade completa (V9) — era stub desde V1, só suportava a FK de AGENDAMENTO.ID_EVENTO_GERADO.';

-- ─── 7. Tabelas novas — .NET owned, nunca existiram no schema real ────────────
-- Ordem respeita dependências de FK. PK segue o padrão já usado em V1
-- (GENERATED BY DEFAULT AS IDENTITY) — funcionalmente equivalente ao
-- SEQ_x.NEXTVAL que o EF espera (ambos deixam a coluna fora do INSERT e leem
-- o valor gerado via RETURNING; já validado empiricamente com CLINICA/V1).

CREATE TABLE MEDICAMENTO (
    ID_MEDICAMENTO     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_MEDICAMENTO     VARCHAR2(200) NOT NULL,
    DS_PRINCIPIO_ATIVO VARCHAR2(500) NOT NULL,
    DS_APRESENTACAO    VARCHAR2(500) NOT NULL,
    DT_CRIACAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO     TIMESTAMP
);
COMMENT ON TABLE MEDICAMENTO IS '.NET owned. Catálogo de medicamentos para prescrições.';

CREATE TABLE NOTIFICACAO (
    ID_NOTIFICACAO NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA     NUMBER(10)    NOT NULL REFERENCES CLINICA(ID_CLINICA),
    ID_TUTOR       NUMBER(10)    REFERENCES TUTOR(ID_TUTOR),
    ID_VETERINARIO NUMBER(10)    REFERENCES VETERINARIO(ID_VETERINARIO),
    DS_TITULO      VARCHAR2(200) NOT NULL,
    DS_MENSAGEM    VARCHAR2(500) NOT NULL,
    ST_LIDA        CHAR(1)       DEFAULT 'N' NOT NULL,
    DT_LEITURA     TIMESTAMP,
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP,
    CONSTRAINT CHK_NOTIF_LIDA CHECK (ST_LIDA IN ('S','N'))
);
COMMENT ON TABLE NOTIFICACAO IS '.NET owned. Notificações internas da clínica (tutor e/ou veterinário).';

CREATE TABLE DISPOSITIVO_IOT (
    ID_DISPOSITIVO NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA     NUMBER(10)    NOT NULL REFERENCES CLINICA(ID_CLINICA),
    CD_DISPOSITIVO VARCHAR2(20)  NOT NULL,
    DS_DESCRICAO   VARCHAR2(500) NOT NULL,
    DS_LOCALIZACAO VARCHAR2(500) NOT NULL,
    DT_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO TIMESTAMP,
    CONSTRAINT UK_DISPOSITIVO_CD UNIQUE (CD_DISPOSITIVO)
);
COMMENT ON TABLE DISPOSITIVO_IOT IS '.NET owned. Sensores ESP32 de temperatura por clínica.';

CREATE TABLE LEITURA_TEMPERATURA (
    ID_LEITURA         NUMBER(10)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DISPOSITIVO_IOT NUMBER(10)  NOT NULL REFERENCES DISPOSITIVO_IOT(ID_DISPOSITIVO),
    VL_TEMPERATURA     NUMBER(5,2) NOT NULL,
    VL_UMIDADE         NUMBER(5,2),
    DT_LEITURA         TIMESTAMP   NOT NULL,
    DT_CRIACAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO     TIMESTAMP
);
COMMENT ON TABLE LEITURA_TEMPERATURA IS '.NET owned. Séries temporais de temperatura/umidade por dispositivo IoT.';

CREATE TABLE ALERTA_TEMPERATURA (
    ID_ALERTA              NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_LEITURA_TEMPERATURA NUMBER(10)    NOT NULL REFERENCES LEITURA_TEMPERATURA(ID_LEITURA),
    DS_TIPO_ALERTA         VARCHAR2(50)  NOT NULL,
    VL_LIMITE              NUMBER(5,2)   NOT NULL,
    DS_MENSAGEM            VARCHAR2(500) NOT NULL,
    ST_RESOLVIDO           CHAR(1)       DEFAULT 'N' NOT NULL,
    DT_CRIACAO             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO         TIMESTAMP,
    CONSTRAINT CHK_ALERTA_RESOLVIDO CHECK (ST_RESOLVIDO IN ('S','N'))
);
COMMENT ON TABLE ALERTA_TEMPERATURA IS '.NET owned. Alertas disparados quando uma leitura ultrapassa o limite configurado.';

CREATE TABLE TRIAGEM_LUNA (
    ID_TRIAGEM         NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA         NUMBER(10)     NOT NULL REFERENCES CLINICA(ID_CLINICA),
    ID_TUTOR           NUMBER(10)     REFERENCES TUTOR(ID_TUTOR),
    ID_PET             NUMBER(10)     REFERENCES PET(ID_PET),
    DS_NIVEL_URGENCIA  VARCHAR2(20)   NOT NULL,
    DS_DESCRICAO       VARCHAR2(2000) NOT NULL,
    ST_ENCAMINHADO_VET CHAR(1)        DEFAULT 'N' NOT NULL,
    DT_TRIAGEM         TIMESTAMP      NOT NULL,
    ST_ATIVA           CHAR(1)        DEFAULT 'S' NOT NULL,
    DT_CRIACAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO     TIMESTAMP,
    CONSTRAINT CHK_TRIAGEM_ENCAMINHADO CHECK (ST_ENCAMINHADO_VET IN ('S','N')),
    CONSTRAINT CHK_TRIAGEM_ATIVA       CHECK (ST_ATIVA IN ('S','N'))
);
COMMENT ON TABLE TRIAGEM_LUNA IS '.NET owned. Resultado de triagens de IA registradas pela Luna via POST /api/v1/luna/triage.';

-- Dependem de EVENTO_CLINICO (e MEDICAMENTO, no caso de PRESCRICAO)

CREATE TABLE EXAME (
    ID_EXAME         NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO_CLINICO NUMBER(10)    NOT NULL REFERENCES EVENTO_CLINICO(ID_EVENTO),
    NM_EXAME          VARCHAR2(200)  NOT NULL,
    DS_RESULTADO      VARCHAR2(1000) NOT NULL,
    DT_REALIZACAO     TIMESTAMP      NOT NULL,
    DT_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP
);
COMMENT ON TABLE EXAME IS '.NET owned. Resultado de exame vinculado a um evento clínico.';

CREATE TABLE VACINA (
    ID_VACINA         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO_CLINICO NUMBER(10)    NOT NULL REFERENCES EVENTO_CLINICO(ID_EVENTO),
    NM_VACINA         VARCHAR2(200) NOT NULL,
    NR_LOTE           VARCHAR2(50)  NOT NULL,
    DS_FABRICANTE     VARCHAR2(200) NOT NULL,
    DT_PROXIMA_DOSE   TIMESTAMP,
    DT_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP
);
COMMENT ON TABLE VACINA IS '.NET owned. Aplicação de vacina vinculada a um evento clínico.';

CREATE TABLE PRESCRICAO (
    ID_PRESCRICAO     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO_CLINICO NUMBER(10)    NOT NULL REFERENCES EVENTO_CLINICO(ID_EVENTO),
    ID_MEDICAMENTO    NUMBER(10)    NOT NULL REFERENCES MEDICAMENTO(ID_MEDICAMENTO),
    DS_POSOLOGIA      VARCHAR2(500) NOT NULL,
    NR_DURACAO_DIAS   NUMBER(10)    NOT NULL,
    DT_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP
);
COMMENT ON TABLE PRESCRICAO IS '.NET owned. Prescrição de medicamento vinculada a um evento clínico (posologia como texto livre — ver D-9).';

CREATE TABLE DOCUMENTO (
    ID_DOCUMENTO      NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO_CLINICO NUMBER(10)    NOT NULL REFERENCES EVENTO_CLINICO(ID_EVENTO),
    NM_ARQUIVO        VARCHAR2(200) NOT NULL,
    DS_TIPO_MIME      VARCHAR2(100) NOT NULL,
    DS_CAMINHO        VARCHAR2(500) NOT NULL,
    NR_TAMANHO_BYTES  NUMBER(19)    NOT NULL,
    DT_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP
);
COMMENT ON TABLE DOCUMENTO IS '.NET owned. Metadados de documento (PDF, imagem) vinculado a um evento clínico — arquivo em storage, path em DS_CAMINHO (ver D-9).';

CREATE TABLE CONSULTA (
    ID_CONSULTA       NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_EVENTO_CLINICO NUMBER(10)     NOT NULL REFERENCES EVENTO_CLINICO(ID_EVENTO),
    DS_MOTIVO         VARCHAR2(200)  NOT NULL,
    DS_ANAMNESE       VARCHAR2(2000),
    DS_EXAME_FISICO   VARCHAR2(2000),
    DS_DIAGNOSTICO    VARCHAR2(1000),
    DT_CONSULTA       TIMESTAMP      NOT NULL,
    ST_ATIVA          CHAR(1)        DEFAULT 'S' NOT NULL,
    DT_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP,
    CONSTRAINT CHK_CONSULTA_ATIVA CHECK (ST_ATIVA IN ('S','N'))
);
ALTER TABLE CONSULTA ADD CONSTRAINT UK_CONSULTA_EVENTO_CLINICO UNIQUE (ID_EVENTO_CLINICO);
COMMENT ON TABLE CONSULTA IS '.NET owned. Detalhe de consulta (1:1 com EVENTO_CLINICO via ID_TIPO_EVENTO=CONSULTA).';
